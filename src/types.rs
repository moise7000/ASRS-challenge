//! Data types of the challenge.
//!
//! ## Contents
//! - `Params`    : (p, q, g), group G of prime order q.
//! - `KeyPair`   : (x, y), with y = g^x mod p.
//! - `Signature` : (s, e), elements of Z/qZ.
//! - `Entry`     : (ctr, m, sigma, tau), one entry of the journal.
//! - `Journal`   : list of `Entry` sorted by publication date.
//! - `Carrier`   : (k, l), indices of the two signatures carrying a secret.
//! - `Challenge` : output of the generation (public part and ground truth).
//!
//! ## Conventions
//! - Elements of Z/qZ are `BigUint` in [0, q).
//! - Elements of G are `BigUint` in [1, p).
//! - Indices are 0-based.
//! - Texts are UTF-8, never normalized after signing.
use chrono::{DateTime, Utc};
use num_bigint::BigUint;


/// Parameters of the group G used by the signature scheme.
pub struct GroupParams {
    /// Large prime modulus (2048 bits in this project).
    pub p:BigUint,
    /// Prime order of the subgroup generated by `g` (256 bits in this project).
    pub q:BigUint,
    /// Generator of the subgroup of order `q` in Z/pZ*.
    pub g:BigUint,
}


/// Key pair of a signer.
pub struct KeyPair {
    pub x:BigUint,
    pub y:BigUint,
}


/// Schnorr signature, a pair of integers.
pub struct Signature {
    pub s:BigUint,
    pub e:BigUint,
}
